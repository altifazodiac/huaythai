// --- สร้าง Object LOTTERY_METADATA จากรายชื่อทั้งหมด ---

type LotteryMeta = { country: 'LA' | 'VN' | 'MY' | 'STOCK' | 'OTHER' };

let combinedMetadata: Record<string, LotteryMeta> = {};

// ฟังก์ชันสำหรับเพิ่มข้อมูลลงใน Object หลัก
const addToMetadata = (names: string[], country: LotteryMeta['country']) => {
  for (const name of names) {
    combinedMetadata[name] = { country };
  }
};

// เพิ่มหวยแต่ละประเภทเข้าไป
addToMetadata(laosLotteries, 'LA');
addToMetadata(vietnamLotteries, 'VN');
addToMetadata(mekongLotteries, 'LA'); 
addToMetadata(stockLotteries, 'STOCK');
addToMetadata(malaysiaLotteries, 'MY');
addToMetadata(otherLotteries, 'OTHER');

export const LOTTERY_METADATA: Record<string, LotteryMeta> = combinedMetadata;